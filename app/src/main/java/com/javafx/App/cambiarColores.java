package com.javafx.App;

import javafx.scene.control.Button;

public class cambiarColores {

    public static void cambiar(Button presente, Button dos,Button tres,Button cuatro){
        presente.setStyle("-fx-background-color:darkgrey");
        dos.setStyle("-fx-background-color:darkorange");
        tres.setStyle("-fx-background-color:darkorange");
        cuatro.setStyle("-fx-background-color:darkorange");
    }

}
